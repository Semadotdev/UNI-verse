    def gce_frame_flags(data):
        """[(frame_no, transp_flag, transp_idx, disposal)] parsed from raw GIF bytes."""
        gct_n = 1 << ((data[10] & 7) + 1)
        i = 13 + 3 * gct_n
        out, fnum = [], -1
        while i < len(data) - 1:
            b = data[i]
            if b == 0x2C:
                fnum += 1
                lc = data[i + 9]
                lsz = 3 * (1 << ((lc & 7) + 1)) if (lc & 0x80) else 0
                i += 10 + lsz + 1
                while data[i] != 0:
                    i += 1 + data[i]
                i += 1
            elif b == 0x21 and i + 1 < len(data) and data[i + 1] == 0xF9:
                packed = data[i + 3]
                out.append((fnum, bool(packed & 1), data[i + 6], (packed >> 2) & 7))
                i += 8
            elif b == 0x21:
                i += 2
                while i < len(data) and data[i] != 0:
                    i += 1 + data[i]
                i += 1
            elif b == 0x3B:
                break
            else:
                i += 1
        return out

