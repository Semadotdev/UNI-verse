def load_env():
    env = {}
    for fn in (".env", ".env.local"):
        pf = PROJ / fn
        if not pf.exists():
            continue
        for line in pf.read_text().splitlines():
            line = line.split("#", 1)[0].strip()
            if "=" in line:
                k, v = line.split("=", 1)
                k = k.strip()
                v = v.strip()
                if (v[:1] == v[-1:] and v[:1] in ("'", '"')) and len(v) >= 2:
                    v = v[1:-1]
                env[k] = v
    return env

def bootstrap_qa_user(env, theme_id="arthur"):
    import subprocess
    supabase_url = env.get("SUPABASE_URL") or env.get("NEXT_PUBLIC_SUPABASE_URL") or ""
    service_key = env.get("SUPABASE_SERVICE_ROLE_KEY") or ""
    db_url = env.get("DATABASE_URL") or env.get("DIRECT_URL") or ""
    if not supabase_url or not service_key or not db_url:
        return None

    code = f"""
const {{ Client }} = require('pg');
const {{ createClient }} = require('@supabase/supabase-js');
(async () => {{
  const sb = createClient({json.dumps(supabase_url)}, {json.dumps(service_key)}, {{
    auth: {{ autoRefreshToken: false, persistSession: false }}
  }});

  // 1. Ensure supabase auth user exists (email confirmed)
  const email = {json.dumps(EMAIL)};
  const password = {json.dumps(PASSWORD)};
  const username = {json.dumps(USERNAME)};
  let uid;
  const listRes = await sb.auth.admin.listUsers({{ filter: 'email=eq.' + email }});
  const existing = (listRes.data?.users || []).find(u => u.email === email);
  if (existing) {{
    uid = existing.id;
    // ensure email is confirmed
    await sb.auth.admin.updateUserById(uid, {{ email_confirm: true }});
  }} else {{
    const createRes = await sb.auth.admin.createUser({{
      email, password, email_confirm: true,
      user_metadata: {{ username }}
    }});
    uid = createRes.data.user.id;
  }}

  // 2. Upsert app User row + purchase + theme
  const c = new Client({{ connectionString: {json.dumps(db_url)} }});
  await c.connect();
  await c.query('INSERT INTO "User" ("id","email","username","coins","createdAt","updatedAt") VALUES ($1,$2,$3,1000,now(),now()) ON CONFLICT ("id") DO UPDATE SET coins=1000',
    [uid, email, username]);
  await c.query('INSERT INTO "PurchasedTheme" ("id","userId","themeId","purchasedAt") VALUES ($1,$2,$3,now()) ON CONFLICT DO NOTHING',
    ['qa-' + uid, uid, {json.dumps(theme_id)}]);
  await c.query('INSERT INTO "UserSettings" ("id","userId","profileThemeId") VALUES ($1,$2,$3) ON CONFLICT ("userId") DO UPDATE SET "profileThemeId" = EXCLUDED."profileThemeId"',
    ['qa-' + uid, uid, {json.dumps(theme_id)}]);
  await c.end();

  // 3. Sign in to get session tokens
  const {{ data, error }} = await sb.auth.signInWithPassword({{ email, password }});
  if (error || !data?.session) {{
    console.error('SIGNIN_FAIL', error?.message || 'no session');
    process.exit(1);
  }}
  console.log(JSON.stringify({{
    access: data.session.access_token,
    refresh: data.session.refresh_token,
    uid: uid
  }}));
}})().catch(e => {{ console.error('BOOT_FAIL', e.message || e); process.exit(1); }});
"""
    r = subprocess.run(["node", "-e", code], capture_output=True, text=True, cwd=PROJ, timeout=30)
    if r.returncode != 0:
        print("  bootstrap stderr:", r.stderr[-500:])
        return None
    try:
        return json.loads(r.stdout.strip())
    except Exception:
        print("  bootstrap stdout:", r.stdout.strip()[:200])
        return None

